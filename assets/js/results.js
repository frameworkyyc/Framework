/* FRAMEWORK — client results (revenue) from one data file
   Reads assets/data/clients.json and fills:
   - the homepage "client revenue represented" total   ([data-revenue-total])
   - each portfolio case study's results strip         ([data-client-results="<id>"])
   Nothing is shown for a client whose revenue is empty, and the homepage total stays hidden until at least one
   client has a figure. Figures are the clients' own revenue, never presented as something Framework generated. */
(function () {
  "use strict";

  var totalBlock = document.querySelector("[data-revenue-total]");
  var strips = Array.prototype.slice.call(document.querySelectorAll("[data-client-results]"));
  if (!totalBlock && !strips.length) return;

  /* "$1,250,000+" — exact figure, as the client gave it (a lower bound). */
  var exact = function (n) { return "$" + Math.floor(n).toLocaleString("en-CA") + "+"; };

  /* "$2.4M+" / "$750K+" — rounded DOWN, so a total never claims more than the figures add up to. */
  var compact = function (n) {
    if (n >= 1e6) {
      var m = Math.floor(n / 1e5) / 10;
      return "$" + (m % 1 === 0 ? m.toFixed(0) : m.toFixed(1)) + "M+";
    }
    if (n >= 1e3) return "$" + Math.floor(n / 1e3) + "K+";
    return "$" + Math.floor(n) + "+";
  };

  var usable = function (client) {
    return client && typeof client.revenue === "number" && isFinite(client.revenue) && client.revenue > 0;
  };

  var fill = function (root, key, text) {
    var el = root.querySelector('[data-fill="' + key + '"]');
    if (el) el.textContent = text;
  };

  fetch("assets/data/clients.json", { credentials: "same-origin" })
    .then(function (res) { if (!res.ok) throw new Error("clients.json " + res.status); return res.json(); })
    .then(function (data) {
      var clients = (data && Array.isArray(data.clients)) ? data.clients : [];
      var withRevenue = clients.filter(usable);

      strips.forEach(function (strip) {
        var id = strip.getAttribute("data-client-results");
        var client = clients.filter(function (c) { return c && c.id === id; })[0];
        if (!usable(client)) return; // no permission / no figure: the strip stays hidden
        fill(strip, "revenue", exact(client.revenue));
        fill(strip, "project", client.project || "");
        strip.hidden = false;
      });

      if (totalBlock && withRevenue.length) {
        var total = withRevenue.reduce(function (sum, c) { return sum + c.revenue; }, 0);
        fill(totalBlock, "total", compact(total));
        fill(totalBlock, "note", "Combined annual revenue of " + (withRevenue.length === 1 ? "the client business" : "the " + withRevenue.length + " client businesses") +
          " that " + (withRevenue.length === 1 ? "has" : "have") + " shared it with us. The clients’ own figures, not revenue generated by Framework.");
        totalBlock.hidden = false;
      }
    })
    .catch(function () { /* data unavailable: leave everything hidden */ });
})();
