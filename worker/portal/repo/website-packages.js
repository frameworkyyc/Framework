/**
 * Website packages (migration 0012): the one downloadable ZIP Framework Admin keeps for a website. Metadata only: the ZIP is a private object in the files bucket (see ../website-files.js,
 * which keeps row and object in step). Every statement names organization_id. A client may only reach a package whose website is published and not archived AND whose own `published` is on;
 * anything else is "not found". Storage keys never leave this module except to the Worker's own file code. A database without migration 0012 reads as "no package".
 */
import { isoTime, requireOrgId, requireId, ok, fail, validActor, isConstraintViolation } from "./common.js";

const missingTable = (err) => /no such table|no such column/i.test(String(err && err.message));
const toPackage = (r) => ({ name: r.name, size: r.size_bytes, published: r.published === 1, publishedAt: r.published_at, uploadedAt: r.uploaded_at, uploadedBy: r.uploaded_by, updatedAt: r.updated_at });

export async function packagesAvailable(db) {
  try { await db.prepare("SELECT 1 FROM website_packages LIMIT 1").first(); return true; } catch { return false; }
}

/** Admin: the package of one website (metadata, never the key), or null. */
export async function getPackageAdmin(db, organizationId, websiteId) {
  requireOrgId(organizationId); requireId(websiteId, "website_id");
  try {
    const r = await db.prepare("SELECT name, size_bytes, published, published_at, uploaded_at, uploaded_by, updated_at FROM website_packages WHERE website_id = ? AND organization_id = ?").bind(websiteId, organizationId).first();
    return r ? toPackage(r) : null;
  } catch (err) { if (missingTable(err)) return null; throw err; }
}

/** Admin: every package of an organization, keyed by website id. */
export async function listPackagesAdmin(db, organizationId) {
  requireOrgId(organizationId);
  try {
    const rows = (await db.prepare("SELECT website_id, name, size_bytes, published, published_at, uploaded_at, uploaded_by, updated_at FROM website_packages WHERE organization_id = ?").bind(organizationId).all()).results;
    return new Map(rows.map((r) => [r.website_id, toPackage(r)]));
  } catch (err) { if (missingTable(err)) return new Map(); throw err; }
}

/** The stored object behind a website's package (key, name, size), for the Worker's own file code only. */
export async function getPackageRecord(db, organizationId, websiteId) {
  requireOrgId(organizationId); requireId(websiteId, "website_id");
  const r = await db.prepare("SELECT storage_key, name, size_bytes, published FROM website_packages WHERE website_id = ? AND organization_id = ?").bind(websiteId, organizationId).first();
  return r ? { key: r.storage_key, name: r.name, size: r.size_bytes, published: r.published === 1 } : null;
}

const audit = (db, organizationId, actor, action, websiteId, at, detail) =>
  db.prepare("INSERT INTO activity_log (id, organization_id, actor_type, actor_ref, action, entity_type, entity_id, detail, visibility, created_at) SELECT ?, ?, 'admin', ?, ?, 'website', ?, ?, 'internal', ? WHERE changes() > 0")
    .bind(crypto.randomUUID(), organizationId, actor.trim(), action, websiteId, detail ? JSON.stringify(detail) : null, at);

/** Set or replace the package of a (not archived) website. A new or replaced file starts UNPUBLISHED: publishing is a separate, deliberate step. Returns the previous key so the caller deletes that object. */
export async function setPackage(db, organizationId, websiteId, file, actor, { now = new Date() } = {}) {
  requireOrgId(organizationId); requireId(websiteId, "website_id");
  if (!validActor(actor)) return fail("invalid_actor");
  const site = await db.prepare("SELECT 1 AS x FROM websites WHERE id = ? AND organization_id = ? AND archived_at IS NULL").bind(websiteId, organizationId).first();
  if (!site) return fail("not_found");
  const prev = await getPackageRecord(db, organizationId, websiteId);
  const at = isoTime(now), by = actor.trim();
  try {
    await db.batch([
      db.prepare(`INSERT INTO website_packages (website_id, organization_id, name, format, content_type, size_bytes, sha256, storage_key, published, published_at, uploaded_at, uploaded_by, updated_at, updated_by)
                  SELECT ?, ?, ?, 'zip', ?, ?, ?, ?, 0, NULL, ?, ?, ?, ? WHERE EXISTS (SELECT 1 FROM websites w WHERE w.id = ? AND w.organization_id = ? AND w.archived_at IS NULL)
                  ON CONFLICT (website_id) DO UPDATE SET name = excluded.name, content_type = excluded.content_type, size_bytes = excluded.size_bytes, sha256 = excluded.sha256, storage_key = excluded.storage_key,
                    published = 0, published_at = NULL, uploaded_at = excluded.uploaded_at, uploaded_by = excluded.uploaded_by, updated_at = excluded.updated_at, updated_by = excluded.updated_by`)
        .bind(websiteId, organizationId, file.name, file.contentType, file.size, file.sha256, file.key, at, by, at, by, websiteId, organizationId),
      audit(db, organizationId, actor, prev ? "website.package.replaced" : "website.package.added", websiteId, at, { size: file.size }),
    ]);
  } catch (err) {
    if (isConstraintViolation(err)) return fail("invalid_combination");
    throw err;
  }
  return ok({ previousKey: prev ? prev.key : null });
}

/** Publish or withdraw the package. Nothing changes (and nothing is audited) when it is already in that state. */
export async function setPackagePublished(db, organizationId, websiteId, published, actor, { now = new Date() } = {}) {
  requireOrgId(organizationId); requireId(websiteId, "website_id");
  if (!validActor(actor)) return fail("invalid_actor");
  const at = isoTime(now), by = actor.trim(), flag = published ? 1 : 0;
  const res = await db.batch([
    db.prepare("UPDATE website_packages SET published = ?, published_at = ?, updated_at = ?, updated_by = ? WHERE website_id = ? AND organization_id = ? AND published <> ?").bind(flag, flag ? at : null, at, by, websiteId, organizationId, flag),
    audit(db, organizationId, actor, flag ? "website.package.published" : "website.package.withdrawn", websiteId, at),
  ]);
  if (res[0].meta.changes === 1) return ok();
  return (await getPackageRecord(db, organizationId, websiteId)) ? ok({ unchanged: true }) : fail("not_found");
}

/** Remove the package row. Returns the key so the caller deletes the object. */
export async function clearPackage(db, organizationId, websiteId, actor, { now = new Date() } = {}) {
  requireOrgId(organizationId); requireId(websiteId, "website_id");
  if (!validActor(actor)) return fail("invalid_actor");
  const prev = await getPackageRecord(db, organizationId, websiteId);
  if (!prev) return fail("not_found");
  const at = isoTime(now);
  await db.batch([
    db.prepare("DELETE FROM website_packages WHERE website_id = ? AND organization_id = ?").bind(websiteId, organizationId),
    audit(db, organizationId, actor, "website.package.removed", websiteId, at),
  ]);
  return ok({ previousKey: prev.key });
}

/** Client: the downloadable package's name and size when the website is visible to the client and the file is published; otherwise null. */
export async function getClientPackage(db, organizationId, websiteId) {
  requireOrgId(organizationId); requireId(websiteId, "website_id");
  try {
    const r = await db.prepare("SELECT p.name, p.size_bytes, p.updated_at FROM website_packages p JOIN websites w ON w.id = p.website_id AND w.organization_id = p.organization_id WHERE p.website_id = ? AND p.organization_id = ? AND p.published = 1 AND w.published = 1 AND w.archived_at IS NULL").bind(websiteId, organizationId).first();
    return r ? { name: r.name, size: r.size_bytes, updatedAt: r.updated_at } : null;
  } catch (err) { if (missingTable(err)) return null; throw err; }
}

/** Client download: the stored object's key, only under the same conditions. For the Worker's own file code. */
export async function getClientPackageRecord(db, organizationId, websiteId) {
  requireOrgId(organizationId); requireId(websiteId, "website_id");
  try {
    const r = await db.prepare("SELECT p.storage_key, p.name, p.size_bytes FROM website_packages p JOIN websites w ON w.id = p.website_id AND w.organization_id = p.organization_id WHERE p.website_id = ? AND p.organization_id = ? AND p.published = 1 AND w.published = 1 AND w.archived_at IS NULL").bind(websiteId, organizationId).first();
    return r ? { key: r.storage_key, name: r.name, size: r.size_bytes } : null;
  } catch (err) { if (missingTable(err)) return null; throw err; }
}

/** Every stored object a package row points to (for the orphan check). */
export async function listPackageStorageKeys(db, organizationId) {
  requireOrgId(organizationId);
  try { return (await db.prepare("SELECT storage_key FROM website_packages WHERE organization_id = ?").bind(organizationId).all()).results.map((r) => r.storage_key); } catch { return []; }
}
