// The homepage combined-client-revenue band: the stated $3M+ floor lives in one attribute on the band (an editorial figure,
// not a database row), the disclaimer is exact, and the script shows the larger of the floor and the database total.
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const home = readFileSync(new URL("index.html", root), "utf8");
const js = readFileSync(new URL("assets/js/results.js", root), "utf8");
const band = home.slice(home.indexOf("data-revenue-total"), home.indexOf("</section>", home.indexOf("data-revenue-total")));

test("revenue band: $3,000,000 floor, exact label and disclaimer, no figure hard-coded in the visible text", () => {
  assert.match(home, /<section [^>]*data-revenue-total data-floor="3000000"/);
  assert.match(band, /Combined annual client revenue<\/p>/);
  assert.ok(band.includes("Combined annual revenue of Framework clients. Not revenue generated by Framework."));
  assert.ok(!/reported by Framework clients/.test(home));
  assert.ok(!/\$3(,000,000|M)\+?<\/span>/.test(band), "the visible figure is produced by the counter, not typed into the page");
  assert.ok(!/\sstyle="/.test(band));
});

test("revenue band: shows the larger of the floor and the database total; floor alone when the API has nothing or fails; no band without either", () => {
  assert.match(js, /getAttribute\("data-floor"\)/);
  assert.match(js, /value < floor/, "a database total below the floor does not lower the figure");
  assert.match(js, /var fallback = function \(\) \{ if \(floor\) present\(format\(floor\), Math\.floor\(floor\)\); else remove\(\);/);
  assert.equal([...js.matchAll(/fallback\(\)/g)].length >= 3, true, "empty response, floor above total, and request failure all use the fallback");
  assert.match(js, /prefers-reduced-motion: reduce/);
});
